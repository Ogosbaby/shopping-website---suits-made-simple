// Renders the SMS tuxedo mark into the source images @capacitor/assets turns
// into Android launcher icons (legacy + adaptive) and splash screens.
//
//   node scripts/generate-app-assets.mjs
//
// Output: mobile/resources/*.png — then run `npm run assets` inside mobile/.
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = resolve(ROOT, "mobile/resources");

const BRAND = "#3B4654";
const PAPER = "#FAF9F6";

// The tuxedo mark, lifted from components/Logo.tsx with an explicit fill.
const MARK = `
  <path d="M38 16 L50 26 L62 16" stroke="currentColor" stroke-width="3.4" stroke-linecap="round" stroke-linejoin="round" />
  <path d="M38 17 L14 25 L30 42 L44 33 Z" fill="currentColor" />
  <path d="M62 17 L86 25 L70 42 L56 33 Z" fill="currentColor" />
  <path d="M50 22 L56.5 28.5 L50 35 L43.5 28.5 Z" fill="currentColor" />
  <path d="M45.5 31.5 L54.5 31.5 L58 62 L50 74 L42 62 Z" fill="currentColor" />
  <circle cx="50" cy="82" r="3" fill="currentColor" />`;

/** A square canvas with the mark centred at `scale` of the canvas width. */
function canvas(size, { background, markScale, colour = "#FFFFFF" }) {
  const inner = size * markScale;
  const scale = inner / 100;
  const offset = (size - inner) / 2;
  const bg = background ? `<rect width="${size}" height="${size}" fill="${background}" />` : "";
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 ${size} ${size}">
    ${bg}
    <g transform="translate(${offset} ${offset}) scale(${scale})" color="${colour}">${MARK}</g>
  </svg>`;
}

async function render(name, svg, size) {
  const path = resolve(OUT, name);
  await sharp(Buffer.from(svg)).resize(size, size).png().toFile(path);
  console.log("wrote", name, `${size}x${size}`);
}

await mkdir(OUT, { recursive: true });

// Legacy launcher icon: full-bleed brand tile.
await render("icon-only.png", canvas(1024, { background: BRAND, markScale: 0.56 }), 1024);

// Adaptive icon layers — the foreground must sit inside the safe zone.
await render("icon-foreground.png", canvas(1024, { background: null, markScale: 0.44 }), 1024);
await render("icon-background.png", canvas(1024, { background: BRAND, markScale: 0.001 }), 1024);

// Square sources @capacitor/assets also understands.
await render("icon.png", canvas(1024, { background: BRAND, markScale: 0.56 }), 1024);

// Splash screens — the mark on the brand colour.
await render("splash.png", canvas(2732, { background: BRAND, markScale: 0.24 }), 2732);
await render("splash-dark.png", canvas(2732, { background: BRAND, markScale: 0.24 }), 2732);

// A paper variant, useful as an alternate launch background.
await render("splash-light.png", canvas(2732, { background: PAPER, markScale: 0.24, colour: BRAND }), 2732);

await writeFile(
  resolve(OUT, "README.md"),
  "# App assets\n\nGenerated by `node scripts/generate-app-assets.mjs` from the SMS tuxedo mark.\n",
  "utf8"
);
